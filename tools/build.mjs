// Prepares the site for an update. Run it from the otter-poll folder:
//   node tools/build.mjs
//
// It does two things.
//
// 1. Packs the scripts the participant page needs for its first screen
//    (js/participant.js and the files it imports) into one file,
//    js/participant.bundle.js. A phone then makes one request for them instead
//    of six, and the first question does not wait on the slowest of six.
//    js/db.js and the Firebase code stay separate and load in the background.
//
// 2. Stamps a new version onto the script and style addresses (tools/stamp.mjs).
//
// Edit the files in js/ as usual. Never edit js/participant.bundle.js by hand,
// and run this again after any change so the bundle matches the source.

import { build } from 'esbuild';

await build({
  entryPoints: ['js/participant.js'],
  outfile: 'js/participant.bundle.js',
  bundle: true,
  format: 'esm',
  target: ['es2020'],
  minify: true,
  legalComments: 'none',
  // Left as a separate file on purpose: it pulls in the large Firebase code.
  external: ['./db.js'],
  banner: { js: '// Built by tools/build.mjs from js/participant.js and the files it imports. Do not edit this file.' },
});
console.log('js/participant.bundle.js built');

await import('./stamp.mjs');
